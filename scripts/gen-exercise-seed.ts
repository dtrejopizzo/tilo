// Writes supabase/migrations/*_seed_exercises.sql from packages/core/src/exercises.ts
import { writeFileSync } from "node:fs"
import { EXERCISES } from "../packages/core/src/exercises"

const q = (s: string) => `'${s.replace(/'/g, "''")}'`
const arr = (a: string[]) => (a.length ? `array[${a.map(q).join(", ")}]::text[]` : "'{}'::text[]")

const rows = EXERCISES.map(
  (e) =>
    `  (${q(e.slug)}, ${q(e.name)}, ${q(e.name_es)}, ${q(e.primary)}, ${arr(e.secondary)}, ${q(e.equipment)}, ${q(e.kind)}, ${e.met})`,
)

const sql = `-- Generated by scripts/gen-exercise-seed.ts from packages/core/src/exercises.ts. Do not edit by hand.
insert into public.exercises (slug, name, name_es, primary_muscle, secondary_muscles, equipment, kind, met)
values
${rows.join(",\n")}
on conflict (slug) where user_id is null do update set
  name = excluded.name, name_es = excluded.name_es, primary_muscle = excluded.primary_muscle,
  secondary_muscles = excluded.secondary_muscles, equipment = excluded.equipment, kind = excluded.kind, met = excluded.met;
`
writeFileSync(new URL("../supabase/migrations/20261008000003_seed_exercises.sql", import.meta.url), sql)
console.log(`Wrote ${EXERCISES.length} exercises`)
